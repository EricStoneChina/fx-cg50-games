static int numToStr(int v, char* buf) {
    char tmp[12];
    int n = 0;
    if (v <= 0) { buf[0] = '0'; buf[1] = '\0'; return 1; }
    while (v > 0) { tmp[n++] = (char)('0' + v % 10); v /= 10; }
    for (int i = 0; i < n; i++) buf[i] = tmp[n - 1 - i];
    buf[n] = '\0';
    return n;
}

static int colorIndexFor(int v) {
    int i = 0;
    while (v > 2 && i < 11) { v >>= 1; i++; }
    return i;
}

