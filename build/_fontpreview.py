def glyph_rows(ch):
    return ["........"] * 2 + INK[ch] + ["........"] * 2

def rgb(h):
    return ((h >> 11) & 31) * 255 // 31, ((h >> 5) & 63) * 255 // 63, (h & 31) * 255 // 31

# current VIVID palette
PAGE = rgb(0xe6fa); BOARD = rgb(0xbd74); EMPTY = rgb(0xce16)
TILES = [rgb(h) for h in (0xf79c,0xdd4b,0xf467,0xe325,0xd1c5,0xb123,
                          0x8a35,0x69d6,0x3a96,0x1c58,0x1513,0x29ea)]
DARKTXT = (34, 32, 28); LIGHTTXT = (237, 230, 216)

def draw_digit(d, x, y, ch, col):
    for r, row in enumerate(glyph_rows(ch)):
        for c, bit in enumerate(row):
            if bit == '#':
                d.point((x + c, y + r), fill=col)

def draw_number(d, x, y, s, col):
    pitch = 9
    w = (len(s) - 1) * pitch + 8
    px = x + (38 - w) // 2
    py = y + (38 - 16) // 2
    for i, ch in enumerate(s):
        draw_digit(d, px + i * pitch, py, ch, col)

def render():
    W, H = 384, 216
    im = Image.new("RGB", (W, H), PAGE)
    d = ImageDraw.Draw(im)
    d.rectangle([12, 26, 12 + 181, 26 + 181], fill=BOARD)
    for bx in (210, 296):
        d.rectangle([bx, 78, bx + 81, 117], fill=BOARD)
    demo = [["2", "4", "8", "16"], ["32", "64", "128", "256"],
            ["512", "1024", "2048", ""], ["2", "4", "", ""]]
    idx_of = {"2": 0, "4": 1, "8": 2, "16": 3, "32": 4, "64": 5,
              "128": 6, "256": 7, "512": 8, "1024": 9, "2048": 10}
    for r in range(4):
        for c in range(4):
            x = 18 + 44 * c; y = 32 + 44 * r
            v = demo[r][c]
            if v == "":
                d.rectangle([x, y, x + 37, y + 37], fill=EMPTY)
                continue
            idx = idx_of[v]
            d.rectangle([x, y, x + 37, y + 37], fill=TILES[idx])
            draw_number(d, x, y, v, DARKTXT if idx < 2 else LIGHTTXT)
    im.resize((W * 2, H * 2), Image.NEAREST).save(
        r"D:\GitHub\fx-cg50-games\_icons\font8x16_board.png")

    # zoomed glyph strip: every digit at 8x then 3x view of 2/4
    strip = Image.new("RGB", (10 * 12, 20), (255, 255, 255))
    ds = ImageDraw.Draw(strip)
    for i, ch in enumerate("0123456789"):
        draw_digit(ds, i * 12 + 2, 2, ch, (0, 0, 0))
    strip.resize((10 * 12 * 6, 20 * 6), Image.NEAREST).save(
        r"D:\GitHub\fx-cg50-games\_icons\font8x16_glyphs.png")
    print("previews saved")

render()
